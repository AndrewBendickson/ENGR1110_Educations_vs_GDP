import os
import numpy as np
import pandas as pd
import plotly.express as px

"""#Creating constants for each excel file

"""

LITERACY_EDU_SPENDING_FILE = "https://github.com/AndrewBendickson/LiteracyFolders/raw/refs/heads/main/Literacy_and_Education_Spending.xlsx"
LITERACY_EDU_GDP_FINAL_FILE = "https://github.com/AndrewBendickson/LiteracyFolders/raw/refs/heads/main/Literacy_Edu_GDP_Final.xlsx"
LITERACY_EDU_GDP_PC_FILE = "https://github.com/AndrewBendickson/LiteracyFolders/raw/refs/heads/main/Literacy_Education_GDPperCapita_Combined.xlsx"

"""#Creating constants for each column name

"""

COL_COUNTRY = "Country Name"
COL_LITERACY = "Literacy Rate"
COL_LIT_YEAR = "Date Literacy Rate was collected"
COL_EDU_PCT_GDP = "Spending on Education (% of GDP)"
COL_EDU_PCT_YEAR = "Date Educational Spending was collected"
COL_GDP_BILLIONS = "GDP (Billions USD)"
COL_GDP_BILLIONS_YEAR = "Date GDP was collected"
COL_TOTAL_EDU_BILLIONS = "Total GDP Spent on Education (Billions USD)"
COL_GDP_PC = "GDP per Capita (US$)"
COL_GDP_PC_YEAR = "Date GDP per Capita was collected"
COL_EDU_SPEND_PC = "Educational Spending per Capita (US$)"

"""#Ultility functions

"""

def load_excel(path):
    df = pd.read_excel(path)
    df.columns = df.columns.str.strip()
    return df

def normalize_literacy(df, column=COL_LITERACY):
    df = df.copy()
    if column in df.columns and df[column].max() > 1.5:
        df[column] = df[column] / 100.0
    return df

def correlation(df, x, y):
    sub = df[[x, y]].dropna()
    if sub.empty:
        return float("nan")
    return sub[x].corr(sub[y])

"""#plot 1: Literacy Rate vs Spending on Education (% of GDP)

"""

def plot_literacy_vs_spending_pct_gdp(df, output_dir):
    temp = normalize_literacy(df).dropna(subset=[COL_LITERACY, COL_EDU_PCT_GDP])
    fig = px.scatter(
        temp,
        x=COL_EDU_PCT_GDP,
        y=COL_LITERACY,
        hover_name=COL_COUNTRY,
        hover_data={COL_LITERACY: ":.3f", COL_EDU_PCT_GDP: ":.2f"},
        title="Literacy Rate vs Spending on Education (% of GDP)",
        template="plotly_white",
    )
    fig.update_layout(
        xaxis_title="Spending on Education (% of GDP)",
        yaxis_title="Literacy Rate (0–1)",
    )
    fig.show()
    filename = os.path.join(output_dir, "plot1_literacy_vs_spending_pct_gdp.html")
    fig.write_html(filename, include_plotlyjs="cdn")

"""#plot 2: Literacy Rate vs GDP (Billions USD)

"""

def plot_literacy_vs_gdp_billions(df, output_dir):
    temp = normalize_literacy(df).dropna(subset=[COL_LITERACY, COL_GDP_BILLIONS])
    temp = temp[temp[COL_GDP_BILLIONS] > 0]
    fig = px.scatter(
        temp,
        x=COL_GDP_BILLIONS,
        y=COL_LITERACY,
        hover_name=COL_COUNTRY,
        hover_data={COL_GDP_BILLIONS: ":.2f"},
        title="Literacy Rate vs GDP (Billions USD)",
        log_x=True,
        template="plotly_white",
    )
    fig.update_layout(
        xaxis_title="GDP (Billions USD, log scale)",
        yaxis_title="Literacy Rate (0–1)",
    )
    fig.show()
    filename = os.path.join(output_dir, "plot2_literacy_vs_gdp_billions.html")
    fig.write_html(filename, include_plotlyjs="cdn")

"""#plot 3: Literacy Rate vs Total GDP Spent on Education (Billions USD)

"""

def plot_literacy_vs_total_edu_spending(df, output_dir):
    temp = normalize_literacy(df).dropna(subset=[COL_LITERACY, COL_TOTAL_EDU_BILLIONS])
    temp = temp[temp[COL_TOTAL_EDU_BILLIONS] > 0].copy()
    np.random.seed(0)
    temp[COL_TOTAL_EDU_BILLIONS] += np.random.uniform(0, 0.05, len(temp))
    fig = px.scatter(
        temp,
        x=COL_TOTAL_EDU_BILLIONS,
        y=COL_LITERACY,
        hover_name=COL_COUNTRY,
        hover_data={COL_TOTAL_EDU_BILLIONS: ":.2f"},
        title="Literacy Rate vs Total GDP Spent on Education (Billions USD)",
        log_x=True,
        template="plotly_white",
    )
    fig.update_layout(
        xaxis_title="Total GDP Spent on Education (Billions USD, log scale)",
        yaxis_title="Literacy Rate (0–1)",
    )
    fig.show()
    filename = os.path.join(output_dir, "plot3_literacy_vs_total_education_spending.html")
    fig.write_html(filename, include_plotlyjs="cdn")

