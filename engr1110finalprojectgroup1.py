"""#plot 6: Educational Spending per Capita vs GDP per Capita colored by Literacy Rate

"""

def plot_edu_spending_vs_gdp_pc_colored_by_literacy(df, output_dir):
    temp = normalize_literacy(df).dropna(subset=[COL_EDU_SPEND_PC, COL_GDP_PC, COL_LITERACY])
    temp = temp[(temp[COL_EDU_SPEND_PC] > 0) & (temp[COL_GDP_PC] > 0)]
    fig = px.scatter(
        temp,
        x=COL_GDP_PC,
        y=COL_EDU_SPEND_PC,
        color=COL_LITERACY,
        color_continuous_scale="Viridis",
        hover_name=COL_COUNTRY,
        hover_data={
            COL_GDP_PC: ":,.0f",
            COL_EDU_SPEND_PC: ":,.2f",
            COL_LITERACY: ":.3f",
        },
        title="Educational Spending per Capita vs GDP per Capita (colored by Literacy Rate)",
        log_x=True,
        log_y=True,
        template="plotly_white",
    )
    fig.update_layout(
        xaxis_title="GDP per Capita (US$, log scale)",
        yaxis_title="Educational Spending per Capita (US$, log scale)",
        coloraxis_colorbar=dict(title="Literacy Rate"),
    )
    fig.show()
    filename = os.path.join(output_dir, "plot6_spending_vs_gdp_per_capita_colored_by_literacy.html")
    fig.write_html(filename, include_plotlyjs="cdn")

"""#main function to run all plots and print correlation summary

"""

def main():
    output_dir = "outputs"
    os.makedirs(output_dir, exist_ok=True)
    df_spending = load_excel(LITERACY_EDU_SPENDING_FILE)
    df_final = load_excel(LITERACY_EDU_GDP_FINAL_FILE)
    df_pc = load_excel(LITERACY_EDU_GDP_PC_FILE)
    plot_literacy_vs_spending_pct_gdp(df_spending, output_dir)
    plot_literacy_vs_gdp_billions(df_final, output_dir)
    plot_literacy_vs_total_edu_spending(df_final, output_dir)
    plot_literacy_vs_gdp_per_capita(df_pc, output_dir)
    plot_literacy_vs_edu_spending_per_capita(df_pc, output_dir)
    plot_edu_spending_vs_gdp_pc_colored_by_literacy(df_pc, output_dir)

    df_final_norm = normalize_literacy(df_final)
    df_pc_norm = normalize_literacy(df_pc)

    pairs = []
    pairs.append(("Literacy vs Spending on Education (% of GDP)",
                    correlation(df_final_norm, COL_EDU_PCT_GDP, COL_LITERACY)))
    pairs.append(("Literacy vs GDP (Billions USD)",
                    correlation(df_final_norm, COL_GDP_BILLIONS, COL_LITERACY)))
    pairs.append(("Literacy vs Total GDP Spent on Education (Billions USD)",
                    correlation(df_final_norm, COL_TOTAL_EDU_BILLIONS, COL_LITERACY)))
    pairs.append(("Literacy vs GDP per Capita (US$)",
                    correlation(df_pc_norm, COL_GDP_PC, COL_LITERACY)))
    pairs.append(("Literacy vs Educational Spending per Capita (US$)",
                    correlation(df_pc_norm, COL_EDU_SPEND_PC, COL_LITERACY)))

    print("Correlation summary (Pearson r):")
    for desc, r in pairs:
        print(f"- {desc}: {r:.3f}")

"""#main function call

"""

if __name__ == "__main__":
    main()

